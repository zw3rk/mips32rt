#!/bin/sh
# run_p5.sh — RC5 lane-L5a gate: PT_INTERP dynamic loading, full auxv,
# /proc/self/* synthesis, interp+dbt parity on LE+BE dynamic binaries.
#
# Builds LE+BE dynamic probes (own .so + dlopen/dlsym, __thread TLS,
# malloc/qsort, getauxval self-checks, argv/envp) with the Debian cross
# toolchains, captures qemu-mipsel/qemu-mips goldens, then requires
# byte-identical stdout+exit under --interp and --dbt, a translator-only
# fork+execve(self)+wait4 round-trip (qemu-user cannot execve a MIPS
# binary), an LD_SHOW_AUXV key-set parity check (qemu guest block vs guest
# ld.so under the translator), an interp-vs-dbt difftest, and a
# host-native unit test of the /proc synthesis in src/os/proc.c.
#
# NOTE (lane L5a): the probes link with an absolute --dynamic-linker and
# an absolute -rpath pointing at the cross sysroot lib dirs, so the loader
# payload resolves through plain host opens.  General sysroot prefixing
# for guest-absolute open/openat/readlink arrives with the RC5 coordinator
# wiring (see the WIRING note in src/os/proc.c); the PT_INTERP mapping,
# relocation, auxv, and --sysroot INTERP lookup machinery under test here
# is identical either way.
#
# Container discipline mirrors tests/run_p4.sh (unique --name,
# --memory 2g --cpus 2, per-command timeouts, docker ps cleanup check).
#
# Acceptance: sh tests/run_p5.sh (exits nonzero on any mismatch).
set -eu
