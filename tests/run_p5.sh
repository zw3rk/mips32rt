/*
 * p5_dyn_probe.c — lane L5a dynamic-linkage probe.
 *
 * Generated by tests/run_p5.sh into gitignored _build scratch (never a
 * repo file, so it cannot collide with lane L5b's tests/test_p5_dyn.c).
 * Output is fully deterministic (no raw addresses printed): every check
 * prints "P5-CHECK <name>: ok", so qemu goldens and both engines compare
 * byte-for-byte.
 */
#define _GNU_SOURCE
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <dlfcn.h>
#include <link.h>
#include <sys/auxv.h>
#include <unistd.h>
#include <errno.h>
#include <sys/types.h>
#include <sys/wait.h>

__thread long p5_main_tls = 7;

static int g_fail = 0;

static void check(const char *name, int ok)
{
    printf("P5-CHECK %s: %s\n", name, ok ? "ok" : "FAIL");
    if (!ok) {
        g_fail++;
    }
}

static int cmp_int(const void *a, const void *b)
{
    int x;
    int y;
    memcpy(&x, a, sizeof(x));
    memcpy(&y, b, sizeof(y));
    return (x > y) - (x < y);
}

static unsigned long g_dlpi_phdr = 0UL;

static int phdr_cb(struct dl_phdr_info *info, size_t size, void *data)
{
    (void)size;
    (void)data;
    if (g_dlpi_phdr == 0UL) {
        g_dlpi_phdr = (unsigned long)info->dlpi_phdr;
    }
    return 1; /* stop after the main executable */
}

static void t_auxv(char *argv0)
{
    unsigned long phdr = getauxval(AT_PHDR);
    const char *execfn;
    check("phdr-present", phdr != 0UL);
    /* The auxv AT_PHDR must agree with the dynamic linker's own view of
     * the main executable (also exercises dl_iterate_phdr). */
    dl_iterate_phdr(phdr_cb, NULL);
    check("phdr-dlpi", phdr != 0UL && g_dlpi_phdr == phdr);
    check("entry-present", getauxval(AT_ENTRY) != 0UL);
    check("base-present", getauxval(AT_BASE) != 0UL);
    check("entry-ne-base", getauxval(AT_ENTRY) != getauxval(AT_BASE));
    check("pagesz", getauxval(AT_PAGESZ) == 4096UL);
    check("clktck", getauxval(AT_CLKTCK) == 100UL);
    check("flags-zero", getauxval(AT_FLAGS) == 0UL);
    check("secure-zero", getauxval(AT_SECURE) == 0UL);
    check("hwcap-zero", getauxval(AT_HWCAP) == 0UL);
    check("hwcap2-zero", getauxval(AT_HWCAP2) == 0UL);
    check("uid-match", getauxval(AT_UID) == (unsigned long)getuid());
    check("gid-match", getauxval(AT_GID) == (unsigned long)getgid());
    check("random-present", getauxval(AT_RANDOM) != 0UL);
    execfn = (const char *)getauxval(AT_EXECFN);
    check("execfn-match", execfn != NULL && strcmp(execfn, argv0) == 0);
}

static void t_libc(int argc, char **argv)
{
    int src[6] = { 5, 1, 4, 0, 3, 2 };
    int *v;
    long sum = 0;
    int i;
    void *h;
    int (*add)(int, int);
    const char *env;

    check("argc", argc == 2);
    check("argv1", argc == 2 && strcmp(argv[1], "p5arg") == 0);
    v = (int *)malloc(6 * sizeof(int));
    check("malloc", v != NULL);
    if (v == NULL) {
        return;
    }
    memcpy(v, src, sizeof(src));
    qsort(v, 6, sizeof(int), cmp_int);
    for (i = 0; i < 6; i++) {
        sum += (long)v[i];
    }
    check("qsort-sum", sum == 15L);
    check("tls", p5_main_tls + 1L == 8L);
    free(v);
    env = getenv("P5_ENV");
    check("env", env != NULL && strcmp(env, "p5-gate") == 0);
    h = dlopen("./libp5dyn.so", RTLD_NOW);
    check("dlopen", h != NULL);
    if (h == NULL) {
        return;
    }
    add = (int (*)(int, int))dlsym(h, "p5_lib_add");
    check("dlsym", add != NULL);
    if (add != NULL) {
        check("dlopen-add", add(20, 22) == 42);
    }
    dlclose(h);
}

/* Translator-only probe (no qemu golden: qemu-user cannot execve a MIPS
 * binary): fork + execve(self as the exec-child marker) + wait4 success
 * path, exercising in-process ELF reload of a DYNAMIC binary (fresh
 * PT_INTERP load, new auxv) plus O_CLOEXEC handling. */
static int t_exec_probe(char **argv, char **envp)
{
    pid_t pid;
    int st;

    fflush(stdout);
    pid = fork();
    if (pid < 0) {
        printf("P5-EXEC-PROBE: SKIP fork errno=%d\n", errno);
        return 2;
    }
    if (pid == 0) {
        char *args[3];

        args[0] = argv[0];
        args[1] = (char *)"p5-exec-child";
        args[2] = NULL;
        execve(argv[0], args, envp);
        _exit(93); /* execve failed */
    }
    if (waitpid(pid, &st, 0) != pid) {
        printf("P5-EXEC-PROBE: FAIL wait\n");
        return 1;
    }
    printf("P5-EXEC-PROBE: exited=%d code=%d\n",
           WIFEXITED(st), WIFEXITED(st) ? WEXITSTATUS(st) : -1);
    if (WIFEXITED(st) && WEXITSTATUS(st) == 42) {
        printf("P5-RESULT: PASS\n");
        return 0;
    }
    printf("P5-RESULT: FAIL\n");
    return 1;
}

int main(int argc, char **argv, char **envp)
{
    setvbuf(stdout, NULL, _IONBF, 0);
    if (argc == 2 && strcmp(argv[1], "p5-exec-child") == 0) {
        printf("P5-EXEC-CHILD: ok\n");
        return 42;
    }
    if (argc == 2 && strcmp(argv[1], "p5-exec-probe") == 0) {
        return t_exec_probe(argv, envp);
    }
    printf("P5-DYN: start argv0=%s\n", argv[0]);
    t_auxv(argv[0]);
    t_libc(argc, argv);
    printf("P5 checks: %d fail\n", g_fail);
    if (g_fail == 0) {
        printf("P5-RESULT: PASS\n");
        return 0;
    }
    printf("P5-RESULT: FAIL\n");
    return 1;
}
