/* p5_proc_unit.c — host-native unit test for the Phase-5 /proc synthesis
 * in src/os/proc.c (generated by tests/run_p5.sh, compiled in the gate
 * container as: cc ... p5_proc_unit.c p5_proc_stubs.c src/os/proc.c).
 * Fails nonzero with a FAIL line; prints P5-PROC-UNIT: PASS on success. */
#define _GNU_SOURCE
#include <errno.h>
#include <fcntl.h>
#include <stdio.h>
#include <string.h>
#include <sys/mman.h>
#include <unistd.h>
#include "mips32rt.h"

extern int mips_proc_classify(const char *path);
extern int mips_proc_open(mips32_ctx_t *ctx, int kind, int flags);
extern long mips_proc_readlink(mips32_ctx_t *ctx, int kind, char *buf,
                               unsigned long bufsz);
extern int mips_proc_maps_text(mips32_ctx_t *ctx, char *buf,
                               unsigned long cap);

static int g_fail = 0;

static void check(const char *name, int ok)
{
    printf("P5-PROC-UNIT %s: %s\n", name, ok ? "ok" : "FAIL");
    if (!ok) {
        g_fail++;
    }
}

/* Read an fd fully; returns bytes or -1. */
static long read_all(int fd, char *buf, unsigned long cap)
{
    unsigned long pos = 0UL;
    if (lseek(fd, 0, SEEK_SET) != 0) {
        return -1;
    }
    for (;;) {
        ssize_t n = read(fd, buf + pos, (size_t)(cap - pos));
        if (n < 0) {
            if (errno == EINTR) {
                continue;
            }
            return -1;
        }
        if (n == 0) {
            return (long)pos;
        }
        pos += (unsigned long)n;
        if (pos >= cap) {
            return -1;
        }
    }
}

static void t_classify(void)
{
    char pidpath[64];
    snprintf(pidpath, sizeof(pidpath), "/proc/%d/maps", (int)getpid());
    check("self-exe", mips_proc_classify("/proc/self/exe") == 1);
    check("self-maps", mips_proc_classify("/proc/self/maps") == 2);
    check("self-cmdline", mips_proc_classify("/proc/self/cmdline") == 3);
    check("self-stat", mips_proc_classify("/proc/self/stat") == 4);
    check("self-auxv", mips_proc_classify("/proc/self/auxv") == 5);
    check("pid-maps", mips_proc_classify(pidpath) == 2);
    check("self-mem-none", mips_proc_classify("/proc/self/mem") == 0);
    check("self-empty-none", mips_proc_classify("/proc/self/") == 0);
    check("self-subdir-none", mips_proc_classify("/proc/self/task/1") == 0);
    check("other-pid-none", mips_proc_classify("/proc/1/maps") == 0);
    check("relative-none", mips_proc_classify("proc/self/maps") == 0);
    check("null-none", mips_proc_classify(NULL) == 0);
    check("tmp-none", mips_proc_classify("/tmp/p5d-le") == 0);
}

static void t_readlink(mips32_ctx_t *ctx)
{
    char buf[4096];
    long n = mips_proc_readlink(ctx, 1, buf, sizeof(buf));
    check("readlink-exe", n == 8L && memcmp(buf, "./p5d-le", 8) == 0);
    check("readlink-trunc", mips_proc_readlink(ctx, 1, buf, 4) == 4L &&
          memcmp(buf, "./p5", 4) == 0);
    check("readlink-maps-einval", mips_proc_readlink(ctx, 2, buf, sizeof(buf)) == -EINVAL);
    check("readlink-none-enoent", mips_proc_readlink(ctx, 0, buf, sizeof(buf)) == -ENOENT);
}

static void t_maps(mips32_ctx_t *ctx)
{
    char buf[8192];
    long n;
    int fd = mips_proc_open(ctx, 2, O_RDONLY);
    check("maps-open", fd >= 0);
    if (fd < 0) {
        return;
    }
    n = read_all(fd, buf, sizeof(buf) - 1U);
    check("maps-read", n > 0);
    if (n > 0) {
        buf[n] = '\0';
        check("maps-text", strstr(buf, "00400000-00401000 r-xp") != NULL);
        check("maps-stack", strstr(buf, "[stack]") != NULL);
        check("maps-exe-name", strstr(buf, "./p5d-le") != NULL);
    }
    close(fd);
    check("maps-wronly-eacces", mips_proc_open(ctx, 2, O_WRONLY) == -EACCES);
    check("maps-rdwr-eacces", mips_proc_open(ctx, 2, O_RDWR) == -EACCES);
}

static void t_cmdline(mips32_ctx_t *ctx)
{
    char buf[256];
    long n;
    static const char want[] = "./p5d-le\0p5arg";
    int fd = mips_proc_open(ctx, 3, O_RDONLY);
    check("cmdline-open", fd >= 0);
    if (fd < 0) {
        return;
    }
    n = read_all(fd, buf, sizeof(buf));
    check("cmdline-bytes", n == (long)sizeof(want) && memcmp(buf, want, sizeof(want)) == 0);
    close(fd);
}

static void t_stat(mips32_ctx_t *ctx)
{
    char buf[1024];
    long n;
    int fields = 0;
    int i;
    int fd = mips_proc_open(ctx, 4, O_RDONLY);
    check("stat-open", fd >= 0);
    if (fd < 0) {
        return;
    }
    n = read_all(fd, buf, sizeof(buf) - 1U);
    check("stat-read", n > 0);
    if (n <= 0) {
        close(fd);
        return;
    }
    buf[n] = '\0';
    /* 52 space-separated fields; the comm "(p5d-le)" holds the one
     * interior space, so fields = spaces (51) with comm counted once. */
    for (i = 0; i < n; i++) {
        if (buf[i] == ' ') {
            fields++;
        }
    }
    check("stat-fields", fields == 51);
    check("stat-comm", strstr(buf, "(p5d-le)") != NULL);
    {
        int pid = -1;
        check("stat-pid", sscanf(buf, "%d", &pid) == 1 && pid == (int)getpid());
    }
    close(fd);
}

static void t_auxv(mips32_ctx_t *ctx)
{
    char buf[256];
    long n;
    int fd;
    check("auxv-open-le", (fd = mips_proc_open(ctx, 5, O_RDONLY)) >= 0);
    if (fd < 0) {
        return;
    }
    n = read_all(fd, buf, sizeof(buf));
    check("auxv-bytes-le", n == (long)ctx->auxv_bytes &&
          memcmp(buf, ctx->auxv_data, (size_t)n) == 0);
    close(fd);
    ctx->cp0_config1 = 1U; /* BE view: every word byte-swapped */
    check("auxv-open-be", (fd = mips_proc_open(ctx, 5, O_RDONLY)) >= 0);
    if (fd < 0) {
        ctx->cp0_config1 = 0U;
        return;
    }
    n = read_all(fd, buf, sizeof(buf));
    {
        /* AT_PHDR key 3 must read back byte-swapped (00 00 00 03) on a
         * BE guest, whatever the host endianness. */
        check("auxv-swapped-be", n == (long)ctx->auxv_bytes && buf[0] == 0 &&
              buf[1] == 0 && buf[2] == 0 && buf[3] == 3);
    }
    close(fd);
    ctx->cp0_config1 = 0U;
}

static void t_exe(mips32_ctx_t *ctx)
{
    char buf[256];
    long n;
    int fd;
    /* Relative exe path that cannot exist: path-string fallback. */
    ctx->exec_path = "./p5-no-such-file";
    check("exe-open-fallback", (fd = mips_proc_open(ctx, 1, O_RDONLY)) >= 0);
    if (fd >= 0) {
        n = read_all(fd, buf, sizeof(buf));
        check("exe-fallback-bytes", n == 17L &&
              memcmp(buf, "./p5-no-such-file", 17) == 0);
        close(fd);
    }
    /* Absolute host path that exists: real read-only ELF handle. */
    ctx->exec_path = "/bin/sh";
    check("exe-open-real", (fd = mips_proc_open(ctx, 1, O_RDONLY)) >= 0);
    if (fd >= 0) {
        ssize_t r;
        lseek(fd, 0, SEEK_SET);
        r = read(fd, buf, 8);
        check("exe-real-elf", r == 8 && memcmp(buf, "\177ELF", 4) == 0);
        close(fd);
    }
    check("exe-wronly-eacces", mips_proc_open(ctx, 1, O_WRONLY) == -EACCES);
    ctx->exec_path = "./p5d-le";
}

int main(void)
{
    static mips32_ctx_t ctx;
    static char *argv[] = { "./p5d-le", "p5arg", NULL };
    static uint32_t auxv[] = { 3U, 0x400034U, 7U, 0x3f000000U,
                               9U, 0x400740U, 0U, 0U };

    memset(&ctx, 0, sizeof(ctx));
    ctx.exec_path = "./p5d-le";
    ctx.guest_argc = 2;
    ctx.guest_argv = argv;
    ctx.regions[0].start = 0x400000U;
    ctx.regions[0].end = 0x401000U;
    ctx.regions[0].prot = (uint32_t)(PROT_READ | PROT_EXEC);
    memcpy(ctx.regions[0].name, "./p5d-le", 9);
    ctx.regions[1].start = 0x7f7f0000U;
    ctx.regions[1].end = 0x7fff0000U;
    ctx.regions[1].prot = (uint32_t)(PROT_READ | PROT_WRITE);
    memcpy(ctx.regions[1].name, "[stack]", 8);
    ctx.region_count = 2;
    memcpy(ctx.auxv_data, auxv, sizeof(auxv));
    ctx.auxv_bytes = sizeof(auxv);

    t_classify();
    t_readlink(&ctx);
    t_maps(&ctx);
    t_cmdline(&ctx);
    t_stat(&ctx);
    t_auxv(&ctx);
    t_exe(&ctx);

    if (g_fail == 0) {
        printf("P5-PROC-UNIT: PASS\n");
        return 0;
    }
    printf("P5-PROC-UNIT: FAIL (%d)\n", g_fail);
    return 1;
}
