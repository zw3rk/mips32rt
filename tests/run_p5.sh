echo "=== P5 LD_SHOW_AUXV key-set parity (qemu guest vs translator guest) ==="
for endian in le be; do
    case $endian in
        le) qemu=qemu-mipsel; guest=/tmp/p5work-le/p5d-le; work=/tmp/p5work-le ;;
        be) qemu=qemu-mips; guest=/tmp/p5work-be/p5d-be; work=/tmp/p5work-be ;;
    esac
    # NB: qemu prints the dump on stdout, guest ld.so on stderr — capture
    # both streams (probe stdout lines never match the AT_ key pattern).
    # LD_SHOW_AUXV is set via a leaf `env` so the `timeout` supervisor
    # itself (a dynamic binary honouring LD_SHOW_AUXV) stays silent.
    ( cd "$work" && env -i P5_ENV=p5-gate PATH=/usr/bin:/bin \
        timeout --kill-after=30s 120s env LD_SHOW_AUXV=1 \
        $qemu -L / "$guest" p5arg \
        >/tmp/p5-$endian.qauxv 2>&1 ) || true
    ( cd "$work" && env -i P5_ENV=p5-gate PATH=/usr/bin:/bin \
        timeout --kill-after=30s 120s env LD_SHOW_AUXV=1 \
        /w/_build/mips32rt --interp -- "$guest" p5arg \
        >/tmp/p5-$endian.tauxv 2>&1 ) || true
    # qemu prints its host auxv first (ending in the host AT_PLATFORM
    # line); the guest block runs from its own AT_PHDR line through
    # AT_BASE_PLATFORM (probe stdout never emits AT_ keys).
    awk '/^AT_PHDR:/{n++} n==2{guest=1} guest{print} /AT_BASE_PLATFORM/{if (guest) exit}' \
        /tmp/p5-$endian.qauxv | grep -o 'AT_[A-Z0-9_]*' | sort -u > /tmp/p5-$endian.qkeys
    grep -o 'AT_[A-Z0-9_]*' /tmp/p5-$endian.tauxv | sort -u > /tmp/p5-$endian.tkeys
    echo "qemu guest keys: $(tr '\n' ' ' </tmp/p5-$endian.qkeys)"
    echo "translator guest keys: $(tr '\n' ' ' </tmp/p5-$endian.tkeys)"
    qonly="$(comm -23 /tmp/p5-$endian.qkeys /tmp/p5-$endian.tkeys | tr '\n' ' ')"
    tonly="$(comm -13 /tmp/p5-$endian.qkeys /tmp/p5-$endian.tkeys | tr '\n' ' ')"
    if [ "$qonly" = "AT_BASE_PLATFORM " ] && [ "$tonly" = "AT_HWCAP2 " ]; then
        echo "P5 PASS: $endian auxv key parity (only BASE_PLATFORM/HWCAP2 differ)"
    else
        p5fail "$endian auxv keys (qemu-only: [$qonly] ours-only: [$tonly])"
    fi
done

