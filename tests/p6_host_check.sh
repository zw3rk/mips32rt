#!/bin/sh
# tests/p6_host_check.sh — Lane L6a acceptance: host-contract CLI/descriptor
# checks (HOST-CONTRACT A32H_ABI 1.0/1.1, G selection, CLI/env contract).
#
# Exercises on AArch64 Linux (no /dev/a32host present):
#   1. no-device fallback (plain run works; AT_EXECFN present in guest auxv)
#   2. MIPS32RT_HOST=none (explicit opt-out) and other HOST values (probe+run)
#   3. --window G selection: explicit 0x0, explicit 0x1_0000_0000 (proven via
#      /proc/PID/maps when the host can reserve it, else honest SKIP),
#      MIPS32RT_WINDOW env, MIPS32RT_EXECFN env, and fail-hard on
#      unusable/invalid windows and descriptors
#   4. --execfn PATH with a custom argv[0] (argv after -- stays verbatim,
#      AT_EXECFN carries PATH)
#   5. --image-fd FD load, including a bogus PATH (the FD wins for image
#      bytes; PATH still feeds argv/AT_EXECFN)
#   6. --help documents the new flags
#
# Builds a tiny static mipsel probe into _build scratch (never a repo file)
# and runs everything inside a bounded docker container (unique --name,
# --memory 2g --cpus 2, per-command timeouts, docker ps cleanup check).
#
# Acceptance: sh tests/p6_host_check.sh exits 0.
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BLD="$ROOT/_build/p6host"
NAME="mips32rt-l6a-$$"
IMG="debian:bookworm-slim"

PASS_COUNT=0
SKIP_COUNT=0

fail() {
    echo "P6-HOST FAIL: $1"
    exit 1
}

pass() {
    PASS_COUNT=$((PASS_COUNT + 1))
    echo "P6-HOST PASS: $1"
}

skip() {
    SKIP_COUNT=$((SKIP_COUNT + 1))
    echo "P6-HOST SKIP: $1"
}

cleanup() {
    docker rm -f "$NAME" >/dev/null 2>&1 || true
}
trap cleanup EXIT INT TERM

echo "=== P6-HOST rebuild translator (host nix cross CC) ==="
nix shell nixpkgs#pkgsCross.aarch64-multiplatform-musl.stdenv.cc -c \
    make -C "$ROOT" clean build CC=aarch64-unknown-linux-musl-gcc
test -x "$ROOT/_build/mips32rt" || fail "no translator binary"

echo "=== P6-HOST stage gate sources (gitignored _build scratch) ==="
mkdir -p "$BLD"
cat > "$BLD/p6probe.c" <<'EOF'
/* p6probe.c — lane L6a host-contract probe (generated by tests/p6_host_check.sh
 * into gitignored _build scratch, never a repo file). Prints guest argv[0]
 * and the AT_EXECFN auxv value; with argv[1] == "wait" it blocks in read(0)
 * so the harness can inspect the translator's /proc/PID/maps window. */
#include <stdio.h>
#include <string.h>
#include <sys/auxv.h>
#include <unistd.h>

int main(int argc, char **argv)
{
    if (argc > 1 && strcmp(argv[1], "wait") == 0) {
        /* Block on stdin so the harness can inspect the translator's
         * /proc/PID/maps window mid-run; EOF (all writers closed) ends it. */
        char c = 0;
        ssize_t n = read(STDIN_FILENO, &c, 1);
        printf("P6 GOT=%d\n", (int)n);
        return 0;
    }
    {
        unsigned long v = getauxval(AT_EXECFN);
        printf("P6 ARGV0=%s\n", argc > 0 ? argv[0] : "(none)");
        printf("P6 EXECFN=%s\n", v != 0UL ? (const char *)v : "(null)");
    }
    return 0;
}
EOF

echo "=== P6-HOST container setup ($IMG) ==="
docker run -d --name "$NAME" --memory 2g --cpus 2 \
    --platform linux/arm64 -v "$ROOT:/w" -w /w "$IMG" sleep 1200
docker exec "$NAME" sh -c \
    'apt-get update -qq && DEBIAN_FRONTEND=noninteractive apt-get install -y -qq gcc-mipsel-linux-gnu libc6-dev-mipsel-cross'

echo "=== P6-HOST build LE probe ==="
docker exec "$NAME" sh -c '
    set -eu
    mipsel-linux-gnu-gcc --version | head -1
    mipsel-linux-gnu-gcc -march=mips32r2 -static -O1 -std=c11 -Wall -Wextra \
        -o /tmp/p6probe /w/_build/p6host/p6probe.c
    mipsel-linux-gnu-readelf -h /tmp/p6probe | grep -E "Class|Machine|Data"
'

echo "=== P6-HOST check 1: no-device fallback, interp (AT_EXECFN present) ==="
docker exec "$NAME" sh -c '
    set -eu
    out=$(timeout --kill-after=30s 120s /w/_build/mips32rt --interp -- /tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" = 0 || { echo "P6-HOST FAIL: default exit $rc"; exit 1; }
    echo "$out" | grep -q "^P6 ARGV0=/tmp/p6probe$" || { echo "P6-HOST FAIL: default argv0"; exit 1; }
    echo "$out" | grep -q "^P6 EXECFN=/tmp/p6probe$" || { echo "P6-HOST FAIL: default execfn"; exit 1; }
' || fail "check 1 (no-device fallback, interp)"
pass "check 1 (no-device fallback, interp, AT_EXECFN present)"

echo "=== P6-HOST check 2: no-device fallback, dbt ==="
docker exec "$NAME" sh -c '
    set -eu
    out=$(timeout --kill-after=30s 120s /w/_build/mips32rt --dbt -- /tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" = 0 || { echo "P6-HOST FAIL: dbt exit $rc"; exit 1; }
    echo "$out" | grep -q "^P6 ARGV0=/tmp/p6probe$" || { echo "P6-HOST FAIL: dbt argv0"; exit 1; }
    echo "$out" | grep -q "^P6 EXECFN=/tmp/p6probe$" || { echo "P6-HOST FAIL: dbt execfn"; exit 1; }
' || fail "check 2 (no-device fallback, dbt)"
pass "check 2 (no-device fallback, dbt)"

echo "=== P6-HOST check 3: MIPS32RT_HOST=none / other values ==="
docker exec "$NAME" sh -c '
    set -eu
    out=$(env MIPS32RT_HOST=none timeout --kill-after=30s 120s /w/_build/mips32rt --interp -- /tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" = 0 || { echo "P6-HOST FAIL: HOST=none exit $rc"; exit 1; }
    echo "$out" | grep -q "^P6 EXECFN=/tmp/p6probe$" || { echo "P6-HOST FAIL: HOST=none execfn"; exit 1; }
    out=$(env MIPS32RT_HOST=auto timeout --kill-after=30s 120s /w/_build/mips32rt --interp -- /tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" = 0 || { echo "P6-HOST FAIL: HOST=auto exit $rc"; exit 1; }
    echo "$out" | grep -q "^P6 EXECFN=/tmp/p6probe$" || { echo "P6-HOST FAIL: HOST=auto execfn"; exit 1; }
' || fail "check 3 (MIPS32RT_HOST handling)"
pass "check 3 (MIPS32RT_HOST=none opt-out, other values probe+run)"

echo "=== P6-HOST check 4: explicit --window 0x0 (G=0 path) ==="
docker exec "$NAME" sh -c '
    set -eu
    out=$(env -u MIPS32RT_WINDOW timeout --kill-after=30s 120s /w/_build/mips32rt --interp --window 0x0 -- /tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" = 0 || { echo "P6-HOST FAIL: window 0x0 exit $rc"; exit 1; }
    echo "$out" | grep -q "^P6 EXECFN=/tmp/p6probe$" || { echo "P6-HOST FAIL: window 0x0 execfn"; exit 1; }
' || fail "check 4 (--window 0x0)"
pass "check 4 (explicit --window 0x0 G=0 path)"

echo "=== P6-HOST check 5: --window 0x100000000 + /proc/PID/maps proof ==="
docker exec "$NAME" sh -c '
    set -eu
    out=$(env -u MIPS32RT_WINDOW timeout --kill-after=30s 120s /w/_build/mips32rt --interp --window 0x100000000 -- /tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    if [ "$rc" != 0 ]; then
        echo "RESULT=SKIP host cannot reserve G=0x100000000"
        exit 0
    fi
    echo "$out" | grep -q "^P6 EXECFN=/tmp/p6probe$" || { echo "RESULT=FAIL execfn"; exit 0; }
    # Deterministic mid-run maps proof: the guest blocks in read(0) on a
    # fifo this shell holds open O_RDWR, so the translator stays alive with
    # its window mapped until our end closes (EOF ends the guest cleanly).
    # NB: no `timeout` wrapper here — GNU timeout forks, so $! would be the
    # wrapper PID, not the translator PID.  A 60s watchdog bounds a hang.
    # NB2: the 4 GiB PROT_NONE reservation is split by the ELF/stack mappings
    # carved into it, so the proof looks for the window-start line plus the
    # stack line at G+0x7f7f0000..G+0x7fff0000 (G=0x100000000 here), never for
    # one single 100000000-200000000 line.
    rm -f /tmp/p6fifo
    mkfifo -m 600 /tmp/p6fifo
    exec 8<>/tmp/p6fifo
    # NB: 8>&- keeps the fifo write end out of the translator itself (it
    # inherits the shell fds); otherwise our close below would never deliver
    # EOF to the blocked guest read.
    env -u MIPS32RT_WINDOW /w/_build/mips32rt --interp --window 0x100000000 -- /tmp/p6probe wait 8>&- < /tmp/p6fifo > /tmp/p6-wait.txt 2>&1 &
    tp=$!
    # Hang bound: the watchdog must not inherit the fifo (fd 8), or the
    # blocked guest read would survive our close and the wait below would
    # hang until the watchdog fires; and the watchdog is always reaped, so
    # a stale watchdog can never SIGKILL a recycled PID in a later run.
    ( exec 8>&- 0</dev/null >/dev/null 2>&1; sleep 60; kill -9 "$tp" 2>/dev/null ) &
    wd=$!
    ok=0
    j=0
    while [ "$j" -lt 10 ]; do
        if grep -qi "^17f7f0000-17fff0000 " "/proc/$tp/maps" 2>/dev/null && \
           grep -qi "^100000000-" "/proc/$tp/maps" 2>/dev/null; then ok=1; break; fi
        if ! kill -0 "$tp" 2>/dev/null; then break; fi
        j=$((j + 1))
        sleep 1
    done
    if [ "$ok" != 1 ]; then
        echo "RESULT=FAIL G=0x100000000 window not observed mid-run"
        exec 8>&-
        wait "$tp" 2>/dev/null || true
        kill "$wd" 2>/dev/null || true
        wait "$wd" 2>/dev/null || true
        rm -f /tmp/p6fifo
        exit 0
    fi
    grep -i "^100000000-" "/proc/$tp/maps" | head -1
    grep -i "^17f7f0000-17fff0000 " "/proc/$tp/maps" | head -1
    exec 8>&-
    wait "$tp" || rc=$?
    rc=${rc:-0}
    kill "$wd" 2>/dev/null || true
    wait "$wd" 2>/dev/null || true
    rm -f /tmp/p6fifo
    test "$rc" = 0 || { echo "RESULT=FAIL wait guest exit $rc"; exit 0; }
    grep -q "^P6 GOT=0$" /tmp/p6-wait.txt || { echo "RESULT=FAIL wait guest output"; exit 0; }
    echo "RESULT=PASS"
' > "$BLD/r-window4g.txt" 2>&1 || fail "check 5 harness error"
cat "$BLD/r-window4g.txt"
if grep -q "^RESULT=PASS" "$BLD/r-window4g.txt"; then
    pass "check 5 (--window 0x100000000 honored, maps-proven)"
elif grep -q "^RESULT=SKIP" "$BLD/r-window4g.txt"; then
    skip "check 5 (--window 0x100000000: host cannot reserve it)"
else
    fail "check 5 (--window 0x100000000)"
fi

echo "=== P6-HOST check 6: MIPS32RT_WINDOW env path ==="
docker exec "$NAME" sh -c '
    set -eu
    out=$(env MIPS32RT_WINDOW=0x100000000 timeout --kill-after=30s 120s /w/_build/mips32rt --interp -- /tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    if [ "$rc" != 0 ]; then
        echo "RESULT=SKIP host cannot reserve MIPS32RT_WINDOW=0x100000000"
        exit 0
    fi
    echo "$out" | grep -q "^P6 EXECFN=/tmp/p6probe$" || { echo "RESULT=FAIL execfn"; exit 0; }
    echo "RESULT=PASS"
' > "$BLD/r-windowenv.txt" 2>&1 || fail "check 6 harness error"
cat "$BLD/r-windowenv.txt"
if grep -q "^RESULT=PASS" "$BLD/r-windowenv.txt"; then
    pass "check 6 (MIPS32RT_WINDOW=0x100000000 honored)"
elif grep -q "^RESULT=SKIP" "$BLD/r-windowenv.txt"; then
    skip "check 6 (MIPS32RT_WINDOW=0x100000000: host cannot reserve it)"
else
    fail "check 6 (MIPS32RT_WINDOW env)"
fi

echo "=== P6-HOST check 7: invalid windows fail hard ==="
docker exec "$NAME" sh -c '
    set -eu
    out=$(env -u MIPS32RT_WINDOW /w/_build/mips32rt --interp --window 0x1 -- /tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" != 0 || { echo "P6-HOST FAIL: window 0x1 unexpectedly ran"; exit 1; }
    echo "$out" | grep -qi "window" || { echo "P6-HOST FAIL: window 0x1 no diagnostic"; exit 1; }
    out=$(env -u MIPS32RT_WINDOW /w/_build/mips32rt --interp --window bogus -- /tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    test "$rc" != 0 || { echo "P6-HOST FAIL: window bogus unexpectedly ran"; exit 1; }
    out=$(env -u MIPS32RT_WINDOW /w/_build/mips32rt --interp --image-fd bogus -- /tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    test "$rc" != 0 || { echo "P6-HOST FAIL: image-fd bogus unexpectedly ran"; exit 1; }
' || fail "check 7 (invalid window/descriptor fail-hard)"
pass "check 7 (invalid --window/--image-fd fail hard with diagnostics)"

echo "=== P6-HOST check 8: --execfn with custom argv[0] ==="
docker exec "$NAME" sh -c '
    set -eu
    out=$(env -u MIPS32RT_EXECFN timeout --kill-after=30s 120s /w/_build/mips32rt --interp --execfn /tmp/p6probe -- custom_argv0 and more 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" = 0 || { echo "P6-HOST FAIL: execfn exit $rc"; exit 1; }
    echo "$out" | grep -q "^P6 ARGV0=custom_argv0$" || { echo "P6-HOST FAIL: execfn argv0"; exit 1; }
    echo "$out" | grep -q "^P6 EXECFN=/tmp/p6probe$" || { echo "P6-HOST FAIL: execfn execfn"; exit 1; }
    out=$(env -u MIPS32RT_EXECFN timeout --kill-after=30s 120s /w/_build/mips32rt --interp --execfn /tmp/p6probe -- lone_argv0 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" = 0 || { echo "P6-HOST FAIL: execfn lone exit $rc"; exit 1; }
    echo "$out" | grep -q "^P6 ARGV0=lone_argv0$" || { echo "P6-HOST FAIL: execfn lone argv0"; exit 1; }
    out=$(env MIPS32RT_EXECFN=/tmp/p6probe timeout --kill-after=30s 120s /w/_build/mips32rt --interp -- env_argv0 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" = 0 || { echo "P6-HOST FAIL: EXECFN env exit $rc"; exit 1; }
    echo "$out" | grep -q "^P6 ARGV0=env_argv0$" || { echo "P6-HOST FAIL: EXECFN env argv0"; exit 1; }
    echo "$out" | grep -q "^P6 EXECFN=/tmp/p6probe$" || { echo "P6-HOST FAIL: EXECFN env execfn"; exit 1; }
' || fail "check 8 (--execfn custom argv[0])"
pass "check 8 (--execfn custom argv[0], lone argv[0], MIPS32RT_EXECFN env)"

echo "=== P6-HOST check 9: --image-fd load (incl. bogus PATH) ==="
docker exec "$NAME" sh -c '
    set -eu
    out=$(timeout --kill-after=30s 120s /w/_build/mips32rt --interp --image-fd 3 -- /tmp/p6probe 3</tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" = 0 || { echo "P6-HOST FAIL: image-fd exit $rc"; exit 1; }
    echo "$out" | grep -q "^P6 ARGV0=/tmp/p6probe$" || { echo "P6-HOST FAIL: image-fd argv0"; exit 1; }
    echo "$out" | grep -q "^P6 EXECFN=/tmp/p6probe$" || { echo "P6-HOST FAIL: image-fd execfn"; exit 1; }
    out=$(timeout --kill-after=30s 120s /w/_build/mips32rt --interp --image-fd 3 -- /no/such/image 3</tmp/p6probe 2>&1) || rc=$?
    rc=${rc:-0}
    echo "$out"
    test "$rc" = 0 || { echo "P6-HOST FAIL: image-fd bogus-path exit $rc"; exit 1; }
    echo "$out" | grep -q "^P6 ARGV0=/no/such/image$" || { echo "P6-HOST FAIL: image-fd bogus-path argv0"; exit 1; }
    echo "$out" | grep -q "^P6 EXECFN=/no/such/image$" || { echo "P6-HOST FAIL: image-fd bogus-path execfn"; exit 1; }
' || fail "check 9 (--image-fd load)"
pass "check 9 (--image-fd load; FD wins over PATH for image bytes)"

echo "=== P6-HOST check 10: --help documents the new flags ==="
docker exec "$NAME" sh -c '
    set -eu
    /w/_build/mips32rt --help > /tmp/p6-help.txt 2>&1 || rc=$?
    rc=${rc:-0}
    test "$rc" = 0 || { echo "P6-HOST FAIL: help exit $rc"; exit 1; }
    grep -q -- "--execfn" /tmp/p6-help.txt || { echo "P6-HOST FAIL: help lacks execfn"; exit 1; }
    grep -q -- "--image-fd" /tmp/p6-help.txt || { echo "P6-HOST FAIL: help lacks image-fd"; exit 1; }
    cat /tmp/p6-help.txt
' || fail "check 10 (--help)"
pass "check 10 (--help documents --execfn/--image-fd)"

echo "=== container cleanup ==="
docker rm -f "$NAME" >/dev/null 2>&1 || true
docker ps
if docker ps --format "{{.Names}}" | grep -qx "$NAME"; then
    fail "container $NAME still present"
fi
trap - EXIT INT TERM

echo "P6-HOST SUMMARY: $PASS_COUNT pass, $SKIP_COUNT skip"
